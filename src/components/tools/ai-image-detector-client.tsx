"use client";

import { useState, type FormEvent } from "react";
import { useAuth } from "@clerk/nextjs";
import { HugeiconsIcon } from "@hugeicons/react";
import { AiImageIcon } from "@hugeicons/core-free-icons";
import { Button } from "@/components/ui/button";
import { ToolShell } from "@/components/tools/tool-shell";
import { ImageDropzone } from "@/components/tools/image-dropzone";
import { ScoreGauge } from "@/components/tools/score-gauge";
import { LoadingCard } from "@/components/tools/loading-card";
import { ErrorCard } from "@/components/tools/error-card";
import { SignInGateButton } from "@/components/tools/sign-in-gate";
import { VerdictBadge, type VerdictTone } from "@/components/tools/verdict-badge";

const LOADING_MESSAGES = [
  "Examining pixel patterns",
  "Checking anatomy, text and physics",
  "Looking for generator artifacts",
  "Finalizing your report",
] as const;

type Verdict = "ai-generated" | "likely-ai" | "uncertain" | "likely-human" | "human";

const VERDICTS: Record<Verdict, { label: string; tone: VerdictTone }> = {
  "ai-generated": { label: "AI-generated", tone: "rose" },
  "likely-ai": { label: "Likely AI-generated", tone: "orange" },
  uncertain: { label: "Uncertain", tone: "amber" },
  "likely-human": { label: "Likely human capture", tone: "sky" },
  human: { label: "Human capture", tone: "emerald" },
};

type ImageAnalysis = {
  aiProbability: number;
  verdict: keyof typeof VERDICTS;
  confidence: "low" | "medium" | "high";
  summary: string;
  possibleGenerator: string | null;
  signals: {
    name: string;
    detail: string;
    severity: "low" | "medium" | "high";
    pointsTo: "ai" | "human";
    kind?: "visual" | "metadata";
  }[];
};

export function AiImageDetectorClient() {
  const { isSignedIn } = useAuth();
  const [file, setFile] = useState<File | null>(null);
  const [status, setStatus] = useState<"idle" | "loading" | "done" | "error">("idle");
  const [result, setResult] = useState<ImageAnalysis | null>(null);
  const [error, setError] = useState<string | null>(null);

  const handleFile = (next: File | null) => {
    setFile(next);
    setResult(null);
    setError(null);
    setStatus("idle");
  };

  const runAnalysis = async () => {
    if (!file) return;
    setStatus("loading");
    setError(null);
    try {
      const body = new FormData();
      body.append("image", file);
      const res = await fetch("/api/tools/ai-image-detector", { method: "POST", body });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? "The analysis failed. Please try again.");
      setResult(data as ImageAnalysis);
      setStatus("done");
    } catch (err) {
      setError(err instanceof Error ? err.message : "The analysis failed. Please try again.");
      setStatus("error");
    }
  };

  const handleSubmit = (e: FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    if (!isSignedIn || !file || status === "loading") return;
    void runAnalysis();
  };

  const verdict = result ? VERDICTS[result.verdict] : null;

  return (
    <ToolShell
      eyebrow="AI image detector"
      title={
        <>
          AI or <span className="text-indigo-600">camera?</span>
        </>
      }
      description="Upload any image and get the probability it was generated by AI — with the visual forensics that explain the verdict."
      contentClassName="max-w-4xl"
      footer="Visual forensic analysis · Your image is never stored"
    >
      <form onSubmit={handleSubmit} className="grid gap-4">
        <ImageDropzone file={file} onFile={handleFile} disabled={status === "loading"} />

        <div className="flex flex-wrap items-center justify-between gap-3">
          <p className="text-xs text-slate-400">PNG, JPG or WebP up to 8 MB — drag, click, or paste</p>
          {isSignedIn ? (
            <Button
              type="submit"
              size="sm"
              disabled={!file || status === "loading"}
              className="rounded-xl bg-indigo-600 px-4 text-white shadow-md shadow-indigo-600/20 hover:bg-indigo-700"
            >
              {status === "loading" ? (
                <>
                  <span className="size-3.5 animate-spin rounded-full border-2 border-white/40 border-t-white" aria-hidden="true" />
                  Analyzing…
                </>
              ) : (
                <>
                  <HugeiconsIcon icon={AiImageIcon} className="size-4" data-icon="inline-start" />
                  Analyze image
                </>
              )}
            </Button>
          ) : (
            <SignInGateButton className="rounded-xl bg-indigo-600 px-4 text-white shadow-md shadow-indigo-600/20 hover:bg-indigo-700">
              Sign in to analyze
            </SignInGateButton>
          )}
        </div>

        {status === "loading" ? (
          <LoadingCard active title="Analyzing your image" messages={LOADING_MESSAGES} />
        ) : null}

        {status === "error" && error ? <ErrorCard message={error} onRetry={() => void runAnalysis()} /> : null}

        {status === "idle" && !result ? (
          <div className="overflow-hidden rounded-3xl border border-indigo-100 bg-slate-950 shadow-xl shadow-indigo-950/10">
            <div className="flex items-center justify-between border-b border-white/10 px-5 py-4">
              <div>
                <p className="text-sm font-semibold text-white">Forensic report</p>
                <p className="mt-0.5 text-xs text-slate-400">Your result will appear here</p>
              </div>
              <HugeiconsIcon icon={AiImageIcon} className="size-5 text-slate-600" />
            </div>
            <div className="grid min-h-40 place-items-center px-5 py-4">
              <p className="text-sm text-slate-600">Drop an image above and run the detector to see your report.</p>
            </div>
          </div>
        ) : null}

        {status === "done" && result && verdict ? (
          <div className="grid gap-4" aria-live="polite">
            <div className="grid items-center gap-6 rounded-3xl border border-slate-200/80 bg-white p-6 shadow-xl shadow-slate-900/6 sm:grid-cols-[auto_1fr]">
              <ScoreGauge value={result.aiProbability} label="AI likelihood" />
              <div>
                <div className="flex flex-wrap items-center gap-2">
                  <VerdictBadge tone={verdict.tone}>{verdict.label}</VerdictBadge>
                  <VerdictBadge tone="slate">Confidence: {result.confidence}</VerdictBadge>
                </div>
                <p className="mt-3 text-sm leading-6 text-slate-600">{result.summary}</p>
                {result.possibleGenerator ? (
                  <p className="mt-4">
                    <span className="inline-flex items-center gap-2 rounded-xl bg-indigo-50 px-3 py-2 text-xs font-semibold text-indigo-700">
                      <HugeiconsIcon icon={AiImageIcon} className="size-4" />
                      Possible source: {result.possibleGenerator}
                    </span>
                  </p>
                ) : null}
              </div>
            </div>

            <div className="overflow-hidden rounded-3xl border border-slate-200/80 bg-white shadow-xl shadow-slate-900/6">
              <div className="border-b border-slate-100 px-5 py-4">
                <p className="text-sm font-semibold text-slate-800">Forensic signals</p>
              </div>
              <ul className="divide-y divide-slate-100">
                {result.signals.map((signal) => (
                  <li key={signal.name} className="flex flex-wrap items-start gap-3 px-5 py-4">
                    <VerdictBadge tone={signal.pointsTo === "ai" ? "rose" : "emerald"}>
                      {signal.pointsTo === "ai" ? "AI signal" : "Human signal"}
                    </VerdictBadge>
                    <div className="min-w-0 flex-1">
                      <p className="text-sm font-semibold text-slate-800">
                        {signal.name}
                        <span className="ml-2 font-normal text-xs text-slate-400">
                          {signal.kind === "metadata" ? "file metadata · " : ""}{signal.severity} impact
                        </span>
                      </p>
                      <p className="mt-1 text-sm leading-6 text-slate-500">{signal.detail}</p>
                    </div>
                  </li>
                ))}
              </ul>
            </div>

            <p className="text-center text-xs text-slate-400">
              Image detection is probabilistic. Treat results as a strong signal, never as proof — sophisticated
              edits and AI-assisted photos sit in a gray zone.
            </p>
          </div>
        ) : null}
      </form>
    </ToolShell>
  );
}
