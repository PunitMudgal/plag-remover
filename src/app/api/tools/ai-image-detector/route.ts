import { generateText, Output, isStepCount, NoOutputGeneratedError } from "ai";
import { z } from "zod";
import { geminiModel } from "@/lib/gemini";
import { clientIp, rateLimit } from "@/lib/rate-limit";
import { badRequest, geminiNotConfigured, requireSignedIn, tooManyRequests } from "@/lib/tool-route";
import { analyzeImageFile, type ForensicSignal } from "@/lib/image-forensics";

export const runtime = "nodejs";

const ACCEPTED_TYPES = ["image/png", "image/jpeg", "image/webp"];
const MAX_SIZE_BYTES = 8 * 1024 * 1024;

/** A signal as returned to the client (visual or deterministic file metadata). */
type Signal = ForensicSignal & { kind?: "visual" | "metadata" };

const analysisSchema = z.object({
  observations: z
    .array(z.string())
    .min(3)
    .describe("Concrete visual observations about this specific image (regions, objects, textures, lighting) written BEFORE any scoring"),
  aiProbability: z.number().min(0).max(100).describe("Probability the image is AI-generated, 0-100"),
  verdict: z.enum(["ai-generated", "likely-ai", "uncertain", "likely-human", "human"]),
  confidence: z.enum(["low", "medium", "high"]),
  summary: z.string().describe("Two or three sentences explaining the overall conclusion"),
  possibleGenerator: z
    .string()
    .nullable()
    .describe("If the style is recognizable, the likely generator (e.g. 'Midjourney-style diffusion model'), otherwise null"),
  signals: z
    .array(
      z.object({
        name: z.string().describe("Short signal name, e.g. 'Inconsistent hands'"),
        detail: z.string().describe("One sentence pointing at the concrete evidence in this image"),
        severity: z.enum(["low", "medium", "high"]),
        pointsTo: z.enum(["ai", "human"]).describe("Whether this signal suggests AI generation or a human capture"),
      }),
    )
    .min(2)
    .describe("The strongest visual signals, AI-pointing and human-pointing, ranked by importance"),
});

export async function POST(request: Request) {
  const authError = await requireSignedIn();
  if (authError) return authError;

  if (!rateLimit(`ai-image-detector:${clientIp(request)}`, 10, 60_000)) {
    return tooManyRequests();
  }

  const configError = geminiNotConfigured();
  if (configError) return configError;

  let form: FormData;
  try {
    form = await request.formData();
  } catch {
    return badRequest("Invalid request body.");
  }

  const file = form.get("image");
  if (!(file instanceof File)) {
    return badRequest("Please attach an image to analyze.");
  }
  if (!ACCEPTED_TYPES.includes(file.type)) {
    return badRequest("Only PNG, JPG and WebP images are supported.");
  }
  if (file.size > MAX_SIZE_BYTES) {
    return badRequest("Image must be smaller than 8 MB.");
  }

  try {
    const imageBytes = new Uint8Array(await file.arrayBuffer());
    const forensics = await analyzeImageFile(imageBytes, file.type);

    // The file itself proves generation — no model call needed.
    if (forensics.definitiveAi) {
      return Response.json({
        aiProbability: 98,
        verdict: "ai-generated",
        confidence: "high",
        summary: `The file's own metadata proves it was generated by ${forensics.definitiveAi.generator}. This is deterministic evidence from the file itself, not a visual guess.`,
        possibleGenerator: forensics.definitiveAi.generator,
        signals: forensics.signals.map((signal) => ({ ...signal, kind: "metadata" as const })),
      });
    }

    const forensicNotes = forensics.notes.length
      ? forensics.notes.map((note) => `- ${note}`).join("\n")
      : "- No metadata found in the file (neutral).";

    const { output } = await generateText({
      model: geminiModel(),
      output: Output.object({ schema: analysisSchema }),
      temperature: 0,
      maxOutputTokens: 16384,
      stopWhen: isStepCount(2),
      messages: [
        {
          role: "user",
          content: [
            {
              type: "text",
              text: `You are a forensic image analyst specializing in detecting AI-generated images (diffusion models like Midjourney, Stable Diffusion, DALL·E, Flux, Imagen, and GANs). You produce decisive, well-calibrated verdicts.

WORKFLOW — follow it strictly:
1. OBSERVE FIRST. In "observations", write 4-8 concrete notes about THIS image: subject, hands/fingers/teeth/eyes, any text or lettering, lighting and shadows, reflections, background, textures, noise character, depth of field. Refer to what is actually visible.
2. THEN SCORE. Base aiProbability strictly on your observations and the file forensics below.

DETERMINISTIC FILE FORENSICS (facts extracted from the file itself — weigh heavily):
${forensicNotes}
Container: ${forensics.format}${forensics.width && forensics.height ? `, ${forensics.width}×${forensics.height}px` : ""}.

CALIBRATION RULES:
- Commit to a direction. Do NOT default to 45-55% or "uncertain" — that verdict is only for genuinely strong conflicting evidence.
- Strong AI evidence: wrong finger/hand/limb counts, gibberish or warped text, physically impossible light/shadows, melted jewelry/glasses, waxy skin, object boundaries that blend, uniform plastic-like textures, meaningless background text.
- Strong human evidence: sensor noise with the right frequency, motion blur, exposure roll-off, gritty real-world detail, imperfect but physically consistent scene — or camera EXIF in the file forensics above.
- Photos of screens, illustrations, CGI renders and 3D art are HUMAN-MADE works; don't call them AI-generated unless they show generator artifacts.
- Set possibleGenerator only when the style is genuinely recognizable; otherwise null.

Examine the attached image now.`,
            },
            { type: "file", mediaType: "image", data: imageBytes },
          ],
        },
      ],
    });

    const { observations: _forensicObservations, ...analysis } = output;
    void _forensicObservations;
    return Response.json({
      ...analysis,
      signals: [
        ...forensics.signals.map((signal) => ({ ...signal, kind: "metadata" as const })),
        ...analysis.signals.map((signal) => ({ ...signal, kind: "visual" as const })),
      ] satisfies Signal[],
    });
  } catch (error) {
    if (NoOutputGeneratedError.isInstance(error)) {
      return Response.json(
        { error: "The analysis came back incomplete. Please try again." },
        { status: 502 },
      );
    }
    console.error("[ai-image-detector]", error);
    return Response.json(
      { error: "Something went wrong while analyzing your image. Please try again." },
      { status: 500 },
    );
  }
}
